/**
 * Assemble the client bundle: esbuild compiles src/client/index.tsx into one
 * CommonJS module with react kept external, then this script wraps it in the
 * loader envelope every DSH client plugin uses
 * (`window.__ModuleLoader__.load({ id, factory })`).
 */
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = resolve(here, '..')
const outFile = resolve(pkgRoot, 'lib/client.js')
const packageName = JSON.parse(readFileSync(resolve(pkgRoot, 'package.json'), 'utf8')).name

const result = await build({
  entryPoints: [resolve(pkgRoot, 'src/client/index.tsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  jsx: 'automatic',
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime', '@deepseek-ai/dsh-client-ui-primitives'],
  legalComments: 'none',
  logLevel: 'warning',
})

const code = result.outputFiles[0].text
const wrapped = `/* lib/client.js — GENERATED by scripts/build-client.mjs; do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageName)},
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
${code}
    return module.exports
  },
})
`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, wrapped)
console.log(`client bundle written: ${outFile} (${wrapped.length} bytes)`)
